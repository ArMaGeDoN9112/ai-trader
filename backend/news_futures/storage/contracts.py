"""Persistence contracts for use cases that share an event snapshot."""

from contextlib import AbstractContextManager, contextmanager
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol

from langgraph.checkpoint.base import BaseCheckpointSaver

from news_futures.schemas.company import EntryReason
from news_futures.trading.terms import CloseIntent, EntryReservation


@dataclass
class TradeEvidence:
    operations: dict[str, str] = field(default_factory=dict)
    receipts: dict[str, str | None] = field(default_factory=dict)
    confirmed_fills: dict[str, list[int | str]] = field(default_factory=dict)
    close_lots: int | None = None


class TradeStore(Protocol):
    def initialize(self) -> None: ...
    def exclusive(self) -> AbstractContextManager[bool]: ...
    def active(self, account_id: str) -> list[dict[str, Any]]: ...
    def evidence(self, cycle_id: str) -> TradeEvidence: ...
    def report(self, *, approval: Path) -> list[dict[str, Any]]: ...
    def require_available(self, account_id: str) -> None: ...
    def reserve(self, entry: EntryReservation) -> None: ...
    def release(self, entry: EntryReservation) -> bool: ...
    def open_cycle(self, entry: EntryReservation, approval: Path, source: str) -> None: ...
    def completed_manual(self, manual: CloseIntent, account_id: str, source: str) -> dict[str, str] | None: ...
    def has_manual_close(self, cycle_id: str, request_id: str) -> bool: ...
    def pending_reviewed_close(self, cycle_id: str) -> str | None: ...
    def set_close_requested(self, cycle_id: str, requested: bool) -> None: ...
    def append(self, cycle_id: str, kind: str, **details: Any) -> None: ...
    def finish(self, cycle_id: str, status: str, reason: str) -> None: ...


class EventStore(Protocol):
    @property
    def trades(self) -> TradeStore: ...

    @property
    def testing_revision(self) -> str | None: ...

    def history(self, *, current_only: bool = False) -> list[dict[str, Any]]: ...
    def latest_decision(self, revision: str) -> dict[str, Any] | None: ...
    def last_decision_id(self) -> int | None: ...
    def current_decision_id(self, revision: str) -> int | None: ...
    def append_decision(self, revision: str, details: dict[str, Any],
                        publication: dict[str, Any], links: list[dict[str, Any]]) -> dict[str, Any]: ...
    def append_revision(self, revision: str, details: dict[str, Any],
                        publication: dict[str, Any], links: list[dict[str, Any]]) -> dict[str, Any]: ...
    def transaction(self, *, immediate: bool = False) -> AbstractContextManager[None]: ...

    def entry_reason(self, account_id: str, position_id: str) -> EntryReason | None: ...
    def save_entry_reason(self, record: EntryReason) -> None: ...


class PublicationStore(Protocol):
    def latest_revision(self, publication_id: str) -> dict[str, Any] | None: ...
    def historical_reprint(self, text: str, published_at: str) -> bool: ...
    def transaction(self) -> AbstractContextManager[None]: ...
    def lock_writes(self) -> None: ...


@contextmanager
def checked_publication(publications: PublicationStore, events: EventStore) -> Iterator[None]:
    # Take locks in event/publication order. Release the source only after the event commit.
    with publications.transaction(), events.transaction(immediate=True):
        publications.lock_writes()
        yield


class RuntimePublications(PublicationStore, Protocol):
    def initialize_runtime(self) -> None: ...
    def pending_revisions(self) -> list[dict[str, Any]]: ...
    def save_result(self, result: dict[str, Any]) -> None: ...
    def save_broker_status(self, status: dict[str, Any], last_confirmed: dict[str, Any] | None) -> None: ...


class OperatorControls(Protocol):
    def pause(self) -> dict[str, Any]: ...
    def saved(self) -> dict[str, Any]: ...
    def close_intent(self, *, pending: bool = False) -> dict[str, Any] | None: ...
    def finish_close(self, request_id: str, status: str, reason: str) -> None: ...


class RuntimeStorage(Protocol):
    @property
    def controls(self) -> OperatorControls: ...

    def publications(self) -> AbstractContextManager[RuntimePublications]: ...
    def events(self, *, testing_revision: str | None = None) -> AbstractContextManager[EventStore]: ...
    def checkpoints(self) -> AbstractContextManager[BaseCheckpointSaver[str]]: ...
